import { app, ipcMain, type IpcMainInvokeEvent } from 'electron';
import { lstat, readFile, realpath, rename, rm, writeFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { join } from 'node:path';
import { LEXICON_PLUGIN_FILE } from '../src/core/lexicon';
import { lexiconPresets } from '../src/core/lexicon-presets';
import { readPresets, type ExportPreset } from '../src/core/presets';
import type { Workflow } from '../src/core/launch';
import type { ExportResult } from '../src/core/types';
import { convertSource } from './convert-source';
import { MediaJobs } from './jobs';
import {
  LexiconRequests,
  installLexiconPlugin,
  lexiconPluginStatus,
  lexiconPluginsFolder,
} from './lexicon-plugin';

const POLL_INTERVAL = 2000;
let requests: LexiconRequests | undefined;

/** Lets the Lexicon plugin import edits whose source was opened from Lexicon. */
export async function recordLexiconExport(result: ExportResult, source: string, format: string) {
  if (!result.path || !requests) return;
  // Lexicon integration problems must never turn a saved file into an export failure.
  await requests
    .record({ source, output: result.path, format, size: result.size, savedAt: Date.now() })
    .catch(() => {});
}

export function configureLexicon(
  trusted: (event: IpcMainInvokeEvent) => void,
  open: (paths: string[], workflow: Workflow) => void,
) {
  const documents = app.getPath('documents'),
    presetsPath = join(app.getPath('userData'), 'lexicon-presets.json');
  // Generated by scripts/prepare-lexicon-plugin.mjs, like the bundled shell actions.
  const bundled =
    process.resourcesPath && !process.defaultApp
      ? join(process.resourcesPath, 'lexicon-plugin', LEXICON_PLUGIN_FILE)
      : join(__dirname, '../build/generated/lexicon-plugin', LEXICON_PLUGIN_FILE);
  // Saved presets live in the renderer's storage; it shares them so Lexicon can offer them.
  let userPresets: ExportPreset[] = [];
  const ready = readFile(presetsPath, 'utf8')
    .then((text) => {
      userPresets = readPresets(text);
    })
    .catch(() => {});
  const jobs = new MediaJobs();
  requests = new LexiconRequests({
    pluginsFolder: lexiconPluginsFolder(documents),
    presets: () => lexiconPresets(userPresets),
    open,
    convert: async (work) => {
      const original = await lstat(work.source);
      if (original.isSymbolicLink() || !original.isFile())
        throw new Error('Only regular audio files can be converted.');
      return convertSource(jobs, {
        ...work,
        source: await realpath(work.source),
        original,
        keepFolders: false,
        namingTemplate: '{name}',
        history: 'conversion',
        changed: 'The track changed while converting.',
      });
    },
  });
  let changing = false;
  ipcMain.handle('lexicon:status', (event) => {
    trusted(event);
    return lexiconPluginStatus(documents, bundled);
  });
  ipcMain.handle('lexicon:install', async (event, enabled: unknown) => {
    trusted(event);
    if (typeof enabled !== 'boolean') throw new Error('Invalid Lexicon plugin setting.');
    if (changing) throw new Error('The Lexicon plugin is already being changed.');
    changing = true;
    try {
      await installLexiconPlugin(documents, bundled, !enabled);
    } finally {
      changing = false;
    }
    return lexiconPluginStatus(documents, bundled);
  });
  let saving = Promise.resolve();
  ipcMain.handle('lexicon:presets', async (event, presets: unknown) => {
    trusted(event);
    const text = JSON.stringify({ version: 1, presets });
    const parsed = readPresets(text);
    if (!Array.isArray(presets) || parsed.length !== presets.length)
      throw new Error('Invalid export presets.');
    await ready;
    userPresets = parsed;
    const task = saving.then(async () => {
      const temporary = `${presetsPath}.${randomUUID()}.tmp`;
      try {
        await writeFile(temporary, text, { mode: 0o600 });
        await rename(temporary, presetsPath);
      } finally {
        await rm(temporary, { force: true });
      }
    });
    saving = task.catch(() => {});
    await task;
  });
  let polling = Promise.resolve();
  const timer = setInterval(() => {
    polling = ready.then(() => requests!.poll()).catch(() => {});
  }, POLL_INTERVAL);
  timer.unref();
  return async () => {
    clearInterval(timer);
    await polling;
    await requests?.stop();
    await saving;
  };
}
