import {
  definitionFor,
  extraInstances,
  instanceRecipe,
  type EffectInstance,
} from './effect-instances';
import { clipRecipe } from './clips';
import { timelineChapters, serializeChapters } from './chapters';
import { textAss } from './overlays';
import { outputCues, serializeCaptionAss, serializeSrt } from './subtitles';
import { frameDimensions } from './geometry';
import type { EditSettings, MediaAsset } from './types';
export interface RecipeResources {
  artwork: string;
  chapters: string;
  captions: string;
  fonts: string;
  text: string;
  image: string;
  lut: string;
}
export const resourcePaths = (
  prefix = 'frame',
  captionMode: EditSettings['subtitles']['mode'] = 'none',
): RecipeResources => ({
  artwork: `${prefix}-artwork.png`,
  chapters: `${prefix}-chapters.ffmetadata`,
  captions: `${prefix}-captions.${captionMode === 'burn' ? 'ass' : 'srt'}`,
  fonts: 'fonts',
  text: `${prefix}-text.ass`,
  image: `${prefix}-image.png`,
  lut: `${prefix}-lut.cube`,
});
export function instancePaths(paths: RecipeResources, instance: EffectInstance): RecipeResources {
  return {
    ...paths,
    lut: `${paths.lut}-${instance.id}.cube`,
    text: `${paths.text}-${instance.id}.ass`,
    image: `${paths.image}-${instance.id}.png`,
    captions: `${paths.captions}-${instance.id}.${instance.settings.subtitles?.mode === 'burn' ? 'ass' : 'srt'}`,
  };
}
export function embeddedCues(edit: EditSettings) {
  return [
    {
      ...edit,
      effectInstances: extraInstances(edit).filter(
        (instance) => definitionFor(instance.effect).scope === 'clip',
      ),
    },
    ...extraInstances(edit, 'captions').map((instance) => instanceRecipe(edit, instance)),
  ]
    .filter((recipe) => recipe.subtitles.mode === 'embed')
    .flatMap((recipe) => outputCues(recipe))
    .sort((a, b) => a.start - b.start);
}
export function burnedCues(edit: EditSettings) {
  return [
    {
      ...edit,
      effectInstances: extraInstances(edit).filter(
        (instance) => definitionFor(instance.effect).scope === 'clip',
      ),
    },
    ...extraInstances(edit, 'captions').map((instance) => instanceRecipe(edit, instance)),
  ]
    .filter((recipe) => recipe.subtitles.mode === 'burn')
    .flatMap((recipe) => outputCues(recipe))
    .sort((a, b) => a.start - b.start);
}
export const burnedCaptionPath = (edit: EditSettings, paths: RecipeResources) =>
  extraInstances(edit, 'captions').length ? `${paths.captions}-burned.ass` : paths.captions;
export const embeddedCaptionPath = (edit: EditSettings, paths: RecipeResources) =>
  extraInstances(edit, 'captions').some((instance) => instance.settings.subtitles?.mode === 'embed')
    ? `${paths.captions}-embedded.srt`
    : paths.captions;
export function recipeImages(edit: EditSettings, paths: RecipeResources) {
  return [
    ...(edit.painting?.image
      ? [{ path: `${paths.image}-paint.png`, data: edit.painting.image }]
      : []),
    ...extraInstances(edit, 'painting').flatMap((instance) =>
      instance.settings.painting?.image
        ? [
            {
              path: `${instancePaths(paths, instance).image}-paint.png`,
              data: instance.settings.painting.image,
            },
          ]
        : [],
    ),
    ...(edit.overlays.image ? [{ path: paths.image, data: edit.overlays.image }] : []),
    ...extraInstances(edit, 'watermark').flatMap((instance) =>
      instance.settings.overlays?.image
        ? [{ path: instancePaths(paths, instance).image, data: instance.settings.overlays.image }]
        : [],
    ),
  ];
}
/** Paths are generated by the engine, never supplied by project documents. */
export function filterPath(path: string): string {
  // FFmpeg parses a filtergraph and then an option value: escape both levels.
  const option = path.replace(/\\/g, '/').replace(/[\\':]/g, (c) => `\\${c}`);
  return option.replace(/[\\'[\],;]/g, (c) => `\\${c}`);
}

export function recipeFiles(
  edit: EditSettings,
  paths: RecipeResources,
  asset?: MediaAsset,
): { path: string; text: string }[] {
  const cues = outputCues(edit);
  const captions =
    edit.subtitles.mode === 'burn'
      ? serializeCaptionAss(
          cues,
          asset ? frameDimensions(asset, edit) : { width: 640, height: 360 },
        )
      : serializeSrt(cues);
  const files =
    edit.subtitles.mode !== 'none' && cues.length ? [{ path: paths.captions, text: captions }] : [];
  if (extraInstances(edit, 'captions').length && burnedCues(edit).length)
    files.push({
      path: burnedCaptionPath(edit, paths),
      text: serializeCaptionAss(
        burnedCues(edit),
        asset ? frameDimensions(asset, edit) : { width: 640, height: 360 },
      ),
    });
  if (edit.includeChapters && timelineChapters(edit).length)
    files.push({ path: paths.chapters, text: serializeChapters(timelineChapters(edit)) });
  if (edit.overlays.text) files.push({ path: paths.text, text: textAss(edit, asset) });
  if (edit.color.lut) files.push({ path: paths.lut, text: edit.color.lut });
  edit.clips?.forEach((clip, index) => {
    const recipe = clipRecipe(edit, clip);
    if (recipe.color.lut && (clip.effects.color?.lut || extraInstances(recipe, 'color').length))
      files.push({ path: `${paths.lut}-clip${index}.cube`, text: recipe.color.lut });
  });
  for (const instance of extraInstances(edit)) {
    const recipe = instanceRecipe(edit, instance),
      resources = instancePaths(paths, instance);
    if (instance.effect === 'captions' && recipe.subtitles.mode !== 'none')
      files.push({
        path: resources.captions,
        text:
          recipe.subtitles.mode === 'burn'
            ? serializeCaptionAss(
                outputCues(recipe),
                asset ? frameDimensions(asset, edit) : { width: 640, height: 360 },
              )
            : serializeSrt(outputCues(recipe)),
      });
    if (instance.effect === 'color' && recipe.color.lut)
      files.push({ path: resources.lut, text: recipe.color.lut });
    if (instance.effect === 'watermark' && recipe.overlays.text)
      files.push({
        path: resources.text,
        text: textAss(recipe, asset, asset ? frameDimensions(asset, edit) : undefined),
      });
  }
  edit.clips?.forEach((clip, index) => {
    for (const instance of extraInstances(clipRecipe(edit, clip), 'color'))
      if (instance.settings.color?.lut)
        files.push({
          path: instancePaths({ ...paths, lut: `${paths.lut}-clip${index}.cube` }, instance).lut,
          text: instance.settings.color.lut,
        });
  });
  if (embeddedCaptionPath(edit, paths) !== paths.captions)
    files.push({ path: embeddedCaptionPath(edit, paths), text: serializeSrt(embeddedCues(edit)) });
  return files;
}
