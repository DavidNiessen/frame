import { textAss } from './overlays';
import { outputCues, serializeCaptionAss, serializeSrt } from './subtitles';
import { frameDimensions } from './geometry';
import type { EditSettings, MediaAsset } from './types';
export interface RecipeResources { captions: string; fonts: string; text: string; image: string; lut: string }
export const resourcePaths = (prefix = 'frame', captionMode: EditSettings['subtitles']['mode'] = 'none'): RecipeResources => ({ captions: `${prefix}-captions.${captionMode === 'burn' ? 'ass' : 'srt'}`, fonts: 'fonts', text: `${prefix}-text.ass`, image: `${prefix}-image.png`, lut: `${prefix}-lut.cube` });
/** Paths are generated by the engine, never supplied by project documents. */
export function filterPath(path: string): string {
  // FFmpeg parses a filtergraph and then an option value: escape both levels.
  const option = path.replace(/\\/g, '/').replace(/[\\':]/g, c => `\\${c}`);
  return option.replace(/[\\'\[\],;]/g, c => `\\${c}`);
}

export function recipeFiles(edit: EditSettings, paths: RecipeResources, asset?: MediaAsset): { path: string; text: string }[] {
  const cues = outputCues(edit);
  const captions = edit.subtitles.mode === 'burn' ? serializeCaptionAss(cues, asset ? frameDimensions(asset, edit) : { width: 640, height: 360 }) : serializeSrt(cues);
  const files = edit.subtitles.mode !== 'none' && cues.length ? [{ path: paths.captions, text: captions }] : [];
  if (edit.overlays.text) files.push({ path: paths.text, text: textAss(edit, asset) });
  if (edit.color.lut) files.push({ path: paths.lut, text: edit.color.lut });
  edit.clips?.forEach((clip, index) => { if (clip.effects.color?.lut) files.push({ path: `${paths.lut}-clip${index}.cube`, text: clip.effects.color.lut }); });
  return files;
}
